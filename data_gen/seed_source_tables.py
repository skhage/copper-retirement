"""Seed SYNTHETIC upstream source tables into a fresh partner catalog.

ACC-DE-SEED-JOB. The copper retirement pipeline and the unified accelerator app
read upstream TMF / ERP / CLM / MDM / 811 tables that a fresh partner workspace
does not have. This module recreates them from ``source_table_contract.json``
(column names + types + categorical domains profiled from the reference
workspace) with deterministic, FK-consistent SYNTHETIC rows:

* every child key is drawn from the generated parent table (FK closure, e.g.
  device_service_allocation.physical_device_id -> physical_device), including
  filtered parents (copper device types, copper service types, SALESFORCE
  crosswalk rows) so the pipeline joins return rows;
* geography is drawn per state from the profiled bounding boxes (the six legacy
  footprint states CO, MN, WA, OR, ID, AZ are always present) and child tables
  inherit lat/lon/state from their geographic_address parent; H3 cells are
  computed with the built-in h3_longlatash3 function;
* every table gets a SYNTHETIC table comment, SYNTHETIC column comments, the
  table property copper.seed.synthetic=true and the governed tag
  telco_project=copper-retirement (best effort if the tag policy is absent).

Safety: an existing table is only overwritten when it carries the
copper.seed.synthetic=true property (i.e. it was written by this seeder), so a
run against the reference workspace never replaces real or curated tables
unless force=True. Use dry_run=True to generate in memory, register temp views
and print the table plan, row counts and join-coverage checks without writing.

Regulatory content is intentionally NOT seeded here: notice periods and
commission names in copper_plant_wire_center_jurisdiction are placeholders;
the cited values live in state_puc_jurisdiction_requirements and
regulatory_source_register.
"""

import datetime as dt
import decimal
import hashlib
import json
import random
import re
from pathlib import Path

CONTRACT_PATH = Path(__file__).with_name("source_table_contract.json")
SEED_MARKER = "copper.seed.synthetic"
DEFAULT_MAX_ROWS = 2000
DEFAULT_SEED = 42
TAG_KEY, TAG_VALUE = "telco_project", "copper-retirement"
PROJECT_SCHEMA = "copper_retirement"
TABLE_COMMENT = (
    "SYNTHETIC seed data generated by the Copper Retirement Solution Accelerator "
    "(data_gen/seed_source_tables.py, contract v{version}). Stand-in for the partner's "
    "{source} source system; contains no real customer, network or regulatory data. "
    "Replace with the partner's production source before go-live."
)

_IDENT = re.compile(r"^[A-Za-z0-9_]+$")
_COL = re.compile(r"([A-Za-z0-9_]+):([a-z]+(?:\(\d+,\d+\))?)")
_H3 = re.compile(r"h3_res(\d+)$")
_GEO_INHERIT = {
    "latitude": "_lat", "longitude": "_lon", "addr_lat": "_lat", "addr_lon": "_lon",
    "state": "_state", "state_code": "_state", "state_or_province": "_state",
}
_STATE_COLS = {"state", "state_code", "primary_state", "home_state", "state_or_province"}
_DEFAULT_DATE_RANGE = ("2015-01-01", "2026-09-30")
# end column -> start column; ends are regenerated after starts so intervals are valid
_END_PAIRS = {
    "expiration_date": "effective_date", "end_date": "start_date",
    "actual_end_date": "actual_start_date", "planned_end_date": "planned_start_date",
    "ticket_expires": "ticket_created", "response_due": "ticket_created",
}


# ---------------------------------------------------------------- helpers
def load_contract(path=None):
    return json.loads(Path(path or CONTRACT_PATH).read_text())


def _q(*parts):
    for p in parts:
        if not _IDENT.match(p):
            raise ValueError(f"Unsafe identifier: {p!r}")
    return ".".join(f"`{p}`" for p in parts)


def _rng(seed, name):
    digest = hashlib.sha256(f"{seed}:{name}".encode()).digest()
    return random.Random(int.from_bytes(digest[:8], "big"))


def parse_cols(spec):
    return _COL.findall(spec["cols"])


def _spark_type(t):
    from pyspark.sql import types as T
    m = re.match(r"decimal\((\d+),(\d+)\)", t)
    if m:
        return T.DecimalType(int(m.group(1)), int(m.group(2)))
    return {
        "bigint": T.LongType(), "int": T.IntegerType(), "smallint": T.ShortType(),
        "double": T.DoubleType(), "float": T.FloatType(), "string": T.StringType(),
        "boolean": T.BooleanType(), "date": T.DateType(), "timestamp": T.TimestampType(),
    }[t]


def _parse_ref(ref):
    base, _, flt = ref.partition("|")
    schema, table, col = base.split(".")
    where = None
    if flt:
        fcol, _, fvals = flt.partition("=")
        where = (fcol, set(fvals.split(",")))
    return f"{schema}.{table}", col, where


def table_order(contract):
    tables = contract["tables"]
    deps = {t: {_parse_ref(r)[0] for r in s.get("fk", {}).values()} - {t} for t, s in tables.items()}
    order, done = [], set()
    while len(order) < len(tables):
        ready = sorted(t for t in tables if t not in done and deps[t] <= done)
        if not ready:
            raise ValueError(f"FK cycle in contract: {sorted(set(tables) - done)}")
        order += ready
        done |= set(ready)
    return order


def _to_date(s):
    return dt.date.fromisoformat(str(s)[:10])


def _to_ts(s):
    return dt.datetime.fromisoformat(str(s)[:19])


def _rand_date(rng, lo, hi):
    lo, hi = _to_date(lo), _to_date(hi)
    return lo + dt.timedelta(days=rng.randint(0, max(0, (hi - lo).days)))


def _cast(value, t):
    if value is None:
        return None
    if t.startswith("decimal"):
        scale = int(re.match(r"decimal\(\d+,(\d+)\)", t).group(1))
        return decimal.Decimal(str(round(float(value), scale)))
    if t in ("bigint", "int", "smallint"):
        return int(float(value))
    if t in ("double", "float"):
        return float(value)
    if t == "boolean":
        return str(value).lower() in ("true", "1", "y")
    if t == "date":
        return _to_date(value)
    if t == "timestamp":
        return _to_ts(value)
    return str(value)


def _key(spec, t, i):
    if t in ("bigint", "int", "smallint"):
        return int(spec.get("pk_start", 1)) + i
    ex = spec.get("pk_ex", "SYN-0000000")
    prefix = re.match(r"[^0-9]*", ex).group()
    width = max(len(ex) - len(prefix), 6)
    return f"{prefix}{'9' + str(i).zfill(width - 1)}"


def _pick_state(rng, geo, footprint, footprint_only=False):
    states = [s for s in geo if not footprint_only or s in footprint]
    weights = [geo[s][0] for s in states]
    return rng.choices(states, weights=weights, k=1)[0]


def _geo_point(rng, geo, state):
    _, lat_lo, lat_hi, lon_lo, lon_hi = geo[state]
    return round(rng.uniform(lat_lo, lat_hi), 5), round(rng.uniform(lon_lo, lon_hi), 5)


def _value(table, c, t, spec, rng, i, row, contract):
    vals = spec.get("vals", {}).get(c)
    rg = spec.get("rng", {}).get(c)
    short = table.split(".")[1]
    if c in spec.get("unique", []):  # non-PK business keys that children join on
        return _cast(int(spec.get("unique_start", 10001)) + i, t)
    if vals:
        return _cast(rng.choice(vals), t)
    if c in _GEO_INHERIT and row.get(_GEO_INHERIT[c]) is not None:
        return _cast(row[_GEO_INHERIT[c]], t)
    if c in _STATE_COLS:
        return row.get("_state") or rng.choice(contract["footprint_states"])
    if (c.endswith("_lat") or c.endswith("centroid_lat")) and row.get("_lat") is not None:
        return _cast(row["_lat"] + rng.uniform(-0.05, 0.05), t)
    if (c.endswith("_lon") or c.endswith("centroid_lon")) and row.get("_lon") is not None:
        return _cast(row["_lon"] + rng.uniform(-0.05, 0.05), t)
    if c in ("wire_center_id", "wire_center_name", "clli_code") and row.get("_state"):
        b, st = row.setdefault("_wc", rng.randint(1, 8)), row["_state"]
        return {"wire_center_id": f"SYN-WC-{st}-{b:02d}",
                "wire_center_name": f"Synthetic {st} Wire Center {b:02d}",
                "clli_code": f"SYN{st}{b:02d}XX"}[c]
    if c == "geographic_coverage_states":
        return ",".join(sorted(set(rng.sample(contract["footprint_states"], 2))))
    if t == "boolean":
        return rng.random() < 0.5
    if t in ("bigint", "int", "smallint"):
        lo, hi = rg or (0, 100)
        return rng.randint(int(lo), int(hi))
    if t in ("double", "float") or t.startswith("decimal"):
        lo, hi = rg or (0.0, 1.0)
        return _cast(rng.uniform(float(lo), float(hi)), t)
    if t == "date":
        return _rand_date(rng, *(rg or _DEFAULT_DATE_RANGE))
    if t == "timestamp":
        lo, hi = (_to_ts(x) for x in (rg or _DEFAULT_DATE_RANGE))
        return lo + dt.timedelta(seconds=rng.randint(0, max(0, int((hi - lo).total_seconds()))))
    # strings
    if c.endswith("_date") or c == "date":
        return _rand_date(rng, *(rg or _DEFAULT_DATE_RANGE)).isoformat()
    if c.lower() in ("name", "title") or c.endswith("_name"):
        return f"Synthetic {short} {i + 1:05d}"
    if c in ("notes", "description", "risk_description", "incident_field_report_text"):
        return f"SYNTHETIC seed record for {short}."
    if c == "geom_wkt" and row.get("_lat") is not None:
        return f"POINT ({row['_lon']} {row['_lat']})"
    if c in ("geographic_coverage_h3",):
        return ""
    return f"SYN-{c.upper()[:16]}-{i + 1:06d}"


# ---------------------------------------------------------------- generation
def generate_rows(contract, max_rows=DEFAULT_MAX_ROWS, scale=1.0, seed=DEFAULT_SEED):
    """Return {source_table: [row dicts incl. hidden _lat/_lon/_state keys]} in FK order."""
    geo, footprint = contract["geo"], contract["footprint_states"]
    out = {}
    for table in table_order(contract):
        spec = contract["tables"][table]
        rng = _rng(seed, table)
        cols = parse_cols(spec)
        pk, fks = spec.get("pk"), spec.get("fk", {})
        n = max(1, min(int(round(spec["rows"] * scale)), max_rows))
        parents = {}
        for col, ref in fks.items():
            ptable, pcol, where = _parse_ref(ref)
            prow = [r for r in out[ptable] if r.get(pcol) is not None
                    and (where is None or str(r.get(where[0])) in where[1])]
            if not prow:
                raise ValueError(f"{table}.{col}: no parent rows in {ref}")
            parents[col] = (prow, pcol)
        unique_rows = None
        if pk in parents:  # 1:1 child keyed by its parent (e.g. copper_risk_target)
            prow, _ = parents[pk]
            n = min(n, len(prow))
            unique_rows = rng.sample(prow, n)
        rows = []
        for i in range(n):
            row, chosen = {}, {}
            for col, (prow, pcol) in parents.items():
                p = unique_rows[i] if (col == pk and unique_rows) else rng.choice(prow)
                chosen[col] = p
                row[col] = p[pcol]
            ga_parent = chosen.get("geographic_address_id")
            if table == "tmf_shared.geographic_address":
                st = _pick_state(rng, geo, footprint)
                row["_state"] = st
                row["_lat"], row["_lon"] = _geo_point(rng, geo, st)
            elif ga_parent is not None:
                row.update({k: ga_parent.get(k) for k in ("_state", "_lat", "_lon")})
            elif any(c in ("latitude", "longitude") for c, _ in cols):
                st = _pick_state(rng, geo, footprint, footprint_only=True)
                row["_state"] = st
                row["_lat"], row["_lon"] = _geo_point(rng, geo, st)
            for child_col, parent_col in spec.get("inherit", {}).items():
                src = chosen.get(pk) or next(iter(chosen.values()), {})
                row[child_col] = src.get(parent_col)
            for c, t in cols:
                if c in row and c not in _GEO_INHERIT:
                    continue
                if c == pk and pk not in parents:
                    row[c] = _key(spec, t, i)
                elif c in _GEO_INHERIT and row.get(_GEO_INHERIT[c]) is not None:
                    row[c] = _cast(row[_GEO_INHERIT[c]], t)
                else:
                    row[c] = _value(table, c, t, spec, rng, i, row, contract)
            types = dict(cols)
            for end_c, start_c in _END_PAIRS.items():
                if end_c in types and start_c in types and row.get(start_c) is not None:
                    base = dt.datetime.fromisoformat(str(row[start_c])[:19])
                    end = base + dt.timedelta(days=rng.randint(1, 3) if end_c == "response_due" else rng.randint(14, 1825))
                    t_end = types[end_c]
                    row[end_c] = end if t_end == "timestamp" else (end.date() if t_end == "date" else end.date().isoformat())
            rows.append(row)
        out[table] = rows
    return out


def to_dataframe(spark, contract, table, rows):
    """Build a typed DataFrame with SYNTHETIC column comments and computed H3 cells."""
    from pyspark.sql import functions as F, types as T
    spec = contract["tables"][table]
    cols = parse_cols(spec)
    fks = spec.get("fk", {})
    fields = []
    for c, t in cols:
        note = f"SYNTHETIC seed value ({t})."
        if c == spec.get("pk"):
            note = f"SYNTHETIC key ({t}); unique per row."
        if c in fks:
            note += f" FK -> {fks[c].split('|')[0]}."
        if _H3.search(c):
            note = f"SYNTHETIC H3 cell computed from the row's lat/lon with h3_longlatash3 ({t})."
        fields.append(T.StructField(c, _spark_type(t), True, {"comment": note}))
    hidden = [T.StructField("_lat", T.DoubleType()), T.StructField("_lon", T.DoubleType())]
    schema = T.StructType(fields + hidden)
    names = [f.name for f in schema.fields]
    data = [tuple(r.get(n) for n in names) for r in rows]
    df = spark.createDataFrame(data, schema)
    for c, t in cols:
        m = _H3.search(c)
        if m:
            fn = "h3_longlatash3string" if t == "string" else "h3_longlatash3"
            expr = F.when(F.col("_lat").isNotNull(), F.expr(f"{fn}(_lon, _lat, {int(m.group(1))})"))
            note = next(f.metadata["comment"] for f in fields if f.name == c)
            df = df.withColumn(c, expr.cast(_spark_type(t))).withMetadata(c, {"comment": note})
    return df.drop("_lat", "_lon")


def target_name(catalog, schema, source_table):
    src_schema, tbl = source_table.split(".")
    return catalog, (schema if src_schema == PROJECT_SCHEMA else src_schema), tbl


# ---------------------------------------------------------------- checks
def coverage_report(dfs):
    """Join-coverage counts that mirror the pipeline/app joins (all must be > 0)."""
    from pyspark.sql import functions as F
    copper_dev = ["cpe", "ont", "olt", "patch_panel"]
    copper_svc = ["voice", "fixed_line", "broadband"]
    pd_ = dfs["tmf_enterprise.physical_device"].where(F.col("device_type").isin(copper_dev))
    cfs = dfs["tmf_service.customer_facing_service"].where(F.col("service_type").isin(copper_svc))
    dsa = dfs["tmf_resource.device_service_allocation"]
    ga = dfs["tmf_shared.geographic_address"]
    cw = dfs["mdm_source.customer_crosswalk"].where("SOURCE_SYSTEM = 'SALESFORCE'")
    cr = dfs["ironclad_clm_source.contract_record"]
    acct = dfs["salesforce_source.account"]
    trx = dfs["oracle_erp_source.ra_customer_trx_all"]
    rrs = dfs["oracle_erp_source.revenue_recognition_schedule"]
    bill = dfs["tmf_customer.bill"]
    lr = dfs["tmf_resource.logical_resource"]
    rbcr = dfs["oracle_erp_source.ra_billed_circuit_rates"]
    dsi = dfs["copper_retirement.dig_safe_incident"]
    cp = dfs["copper_retirement.contractor_performance"]
    fp = ["CO", "MN", "WA", "OR", "ID", "AZ"]
    return {
        "copper_device_service_links": dsa.join(pd_, "physical_device_id")
            .join(cfs, dsa.service_id == cfs.customer_facing_service_id).count(),
        "footprint_copper_devices": pd_.join(ga.select("geographic_address_id", "state_or_province"), "geographic_address_id")
            .where(F.col("state_or_province").isin(fp)).count(),
        "contracts_resolving_to_customer": cr.join(acct, cr.account_id == acct.Id)
            .join(cw, cr.account_id == cw.SOURCE_PARTY_ID).count(),
        "deferred_rev_rows_with_bill": rrs.where("STATUS = 'DEFERRED'").join(trx, "CUSTOMER_TRX_ID")
            .join(bill, trx.TMF_BILL_ID == bill.bill_id).count(),
        "billed_circuits_on_copper_devices": rbcr.join(lr, rbcr.SERVICE_CIRCUIT_ID == lr.logical_resource_id)
            .join(pd_, "physical_device_id").count(),
        "dig_incidents_with_contractor": dsi.join(cp, "bp_agreement_id").count(),
        "decommission_work_orders": dfs["tmf_enterprise.work"].where("type = 'decommission'").count(),
        "plan_tab_projects": dfs["tmf_enterprise.project"]
            .where(F.col("type").isin("infrastructure_upgrade", "network_rollout")).count(),
        "copper_risk_targets": dfs["copper_retirement.copper_risk_target"].count(),
    }


# ---------------------------------------------------------------- writer
def _is_seeded(spark, fq):
    props = {r[0]: r[1] for r in spark.sql(f"SHOW TBLPROPERTIES {fq}").collect()}
    return props.get(SEED_MARKER) == "true"


def seed_tables(spark, catalog, schema, max_rows=DEFAULT_MAX_ROWS, scale=1.0,
                seed=DEFAULT_SEED, dry_run=False, force=False, contract_path=None):
    """Generate and (unless dry_run) write every contract table. Returns a manifest dict."""
    contract = load_contract(contract_path)
    rows = generate_rows(contract, max_rows=max_rows, scale=scale, seed=seed)
    dfs, manifest, refused = {}, [], []
    for table in table_order(contract):
        cat, sch, tbl = target_name(catalog, schema, table)
        fq = _q(cat, sch, tbl)
        df = to_dataframe(spark, contract, table, rows[table])
        dfs[table] = df
        entry = {"source": table, "target": f"{cat}.{sch}.{tbl}", "rows": len(rows[table]),
                 "columns": len(parse_cols(contract["tables"][table])), "written": False}
        if dry_run:
            df.createOrReplaceTempView(f"seed_{sch}__{tbl}")
        else:
            spark.sql(f"CREATE SCHEMA IF NOT EXISTS {_q(cat, sch)}")
            if spark.catalog.tableExists(f"{cat}.{sch}.{tbl}") and not force and not _is_seeded(spark, fq):
                refused.append(entry["target"])
                entry["refused"] = "exists without copper.seed.synthetic=true (not overwritten)"
                manifest.append(entry)
                continue
            df.write.mode("overwrite").option("overwriteSchema", "true").saveAsTable(f"{cat}.{sch}.{tbl}")
            comment = TABLE_COMMENT.format(version=contract["version"], source=table).replace("'", "")
            spark.sql(f"COMMENT ON TABLE {fq} IS '{comment}'")
            spark.sql(f"ALTER TABLE {fq} SET TBLPROPERTIES ('{SEED_MARKER}' = 'true', "
                      f"'copper.seed.contract_version' = '{int(contract['version'])}', 'copper.seed.seed' = '{int(seed)}')")
            try:
                spark.sql(f"ALTER TABLE {fq} SET TAGS ('{TAG_KEY}' = '{TAG_VALUE}')")
            except Exception as exc:  # governed tag policy may not exist in a fresh workspace
                entry["tag_warning"] = str(exc)[:200]
            entry["written"] = True
        manifest.append(entry)
    report = coverage_report(dfs)
    return {"dry_run": dry_run, "catalog": catalog, "schema": schema, "seed": seed,
            "max_rows": max_rows, "tables": manifest, "refused": refused, "coverage": report}
